/** שפת הממשק הנוכחית, מ-localStorage, עם נפילה לעברית. */
function uiLang() {
    try {
        const l = localStorage.getItem('ui_lang');
        if (l && I18N[l]) return l;
    } catch (e) { /* דפדפן פרטי/חסום — נופלים לברירת המחדל */ }
    return 'he';
}

/** קובע את שפת הממשק ושומר מקומית. */
function setUiLang(code) {
    try { localStorage.setItem('ui_lang', code); } catch (e) { /* ניתן להתעלם */ }
}

/** כיוון הכתיבה של שפה (rtl/ltr). */
function langDir(code) {
    const m = I18N_LANGS.find((l) => l.code === code);
    return m ? m.dir : 'rtl';
}

/** מתרגם מפתח, עם החלפת {name} מתוך params. נפילה: שפה→עברית→המפתח. */
function t(key, params) {
    const lang = uiLang();
    let s = (I18N[lang] && I18N[lang][key]) ?? I18N.he[key] ?? key;
    if (params) {
        for (const k in params) s = s.split('{' + k + '}').join(params[k]);
    }
    return s;
}

/** מחיל את כל התרגומים הסטטיים על ה-DOM, ומעדכן lang/dir של הדף. */
function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
        el.setAttribute('placeholder', t(el.dataset.i18nPh));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.setAttribute('title', t(el.dataset.i18nTitle));
    });
    const lang = uiLang();
    document.documentElement.lang = lang;
    document.documentElement.dir = langDir(lang);
}
