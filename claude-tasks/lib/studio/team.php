/**
 * מוודא שהמנהל ושלושת חברי הצוות קיימים בפלטפורמה. נוצרים פעם אחת לכל משתמש, ומתעדכנים (גרסה חדשה)
 * רק כשההגדרה או המודל השתנו. מחזיר ['lead' => [id, version], 'members' => [...]].
 */
function studioEnsureTeam(array $user, string $key, string $model): array {
    $uid = (int) $user['id'];
    $s = studioSettings($uid);
    $team = is_array($s['team'] ?? null) ? $s['team'] : [];
    $roles = studioTeamRoles();
    $hash = sha1(STUDIO_TEAM_REV . '|' . STUDIO_AGENT_REV . '|' . $model . '|' . json_encode($roles, JSON_UNESCAPED_UNICODE));
    if (($team['hash'] ?? '') === $hash && ($team['lead']['id'] ?? '') !== '') return $team;

    $members = is_array($team['members'] ?? null) ? $team['members'] : [];
    foreach ($roles as $k => $role) {
        $def = studioTeamMemberDef($role, $model);
        $a = ($members[$k]['id'] ?? '') === '' ? maCreateAgent($key, $def) : maUpdateAgent($key, (string) $members[$k]['id'], $def);
        $id = (string) ($a['id'] ?? ($members[$k]['id'] ?? ''));
        if ($id === '') throw new MaError('הפלטפורמה לא החזירה מזהה לחבר הצוות "' . $role['name'] . '"');
        $members[$k] = ['id' => $id, 'version' => (int) ($a['version'] ?? ($members[$k]['version'] ?? 1))];
        // נשמר אחרי כל אחד: כשל באמצע לא יוצר את אותו סוכן פעמיים בניסיון הבא
        $team['members'] = $members;
        studioSaveSettings($uid, ['team' => $team]);
    }

    $leadDef = studioTeamLeadDef($model, $members);
    $a = ($team['lead']['id'] ?? '') === '' ? maCreateAgent($key, $leadDef) : maUpdateAgent($key, (string) $team['lead']['id'], $leadDef);
    $leadId = (string) ($a['id'] ?? ($team['lead']['id'] ?? ''));
    if ($leadId === '') throw new MaError('הפלטפורמה לא החזירה מזהה למנהל הצוות');
    $team['lead'] = ['id' => $leadId, 'version' => (int) ($a['version'] ?? ($team['lead']['version'] ?? 1))];
    $team['hash'] = $hash;
    studioSaveSettings($uid, ['team' => $team]);
    return $team;
}
