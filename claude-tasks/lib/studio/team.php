/** הגדרת חבר צוות בפלטפורמה. אותן הרשאות מלאות כמו לסוכן היחיד; הגבול בין התפקידים הוא ההנחיה. */
function studioTeamMemberDef(array $role, string $model): array {
    return [
        'name'        => $role['name'],
        'description' => $role['description'],
        'model'       => $model,
        'system'      => $role['system'],
        'tools'       => [[
            'type' => 'agent_toolset_20260401',
            'default_config' => ['enabled' => true, 'permission_policy' => ['type' => 'always_allow']],
        ]],
    ];
}

/** הגדרת המנהל: אותו סוכן בסיס, עם רשימת חברי הצוות. ההנחיה לכל שיחה מגיעה ביצירת הסשן. */
function studioTeamLeadDef(string $model, array $members): array {
    $def = studioAgentDef($model);
    $def['name'] = 'מטלות לקלוד — מנהל צוות';
    $def['description'] = 'מנהל צוות פיתוח: מדבר עם בעל הלוח, מחלק מטלות לאפיון, קוד ובקרה, ואחראי על ה-PR.';
    $def['multiagent'] = [
        'type'   => 'coordinator',
        'agents' => array_map(fn ($m) => ['type' => 'agent', 'id' => (string) $m['id'], 'version' => (int) $m['version']], array_values($members)),
    ];
    return $def;
}

