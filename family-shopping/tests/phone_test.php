require_once __DIR__ . '/../includes/currency.php';
require_once __DIR__ . '/../includes/phone.php';

$pass = 0;
$fail = 0;

function check($label, $actual, $expected) {
    global $pass, $fail;

    if ($actual === $expected) {
        $pass++;
        echo "  ok   $label\n";
    } else {
        $fail++;
        echo "  FAIL $label — קיבלנו: " . var_export($actual, true)
            . " | ציפינו: " . var_export($expected, true) . "\n";
    }
}

// ============================================================
echo "\n1. נרמול\n";
// ============================================================

check('מספר נקי נשאר',            normalizePhone('0501234567'),     '0501234567');
check('מקפים מוסרים',             normalizePhone('050-123-4567'),   '0501234567');
check('רווחים מוסרים',            normalizePhone('050 123 4567'),   '0501234567');
check('סוגריים מוסרים',           normalizePhone('(050) 1234567'),  '0501234567');
check('רווחים בקצוות',            normalizePhone('  0501234567  '), '0501234567');
check('קידומת בינלאומית נשמרת',   normalizePhone('+972501234567'),  '+972501234567');
check('קידומת עם רווחים',         normalizePhone('+972 50 123 4567'), '+972501234567');
check('00 מתורגם לפלוס',          normalizePhone('00972501234567'), '+972501234567');
check('קווי בן 9',                normalizePhone('02-1234567'),     '021234567');

echo "\n1ב. מה נדחה\n";
